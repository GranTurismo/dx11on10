#!/usr/bin/env python3
"""Generate the body of the ID3D11DeviceContext4 wrapper from the MinGW d3d11_3.h C vtable.

Every method forwards to the real context through the interface that declares it;
methods named in INTERCEPTED go to Hk_<name>(real, ...) in context.cpp instead.

usage: gen_context_wrapper.py <d3d11_3.h> <out.inc>
"""
import re
import sys

INTERCEPTED = {
    'VSSetShader', 'PSSetShader', 'GSSetShader', 'HSSetShader', 'DSSetShader', 'CSSetShader',
    'IASetPrimitiveTopology', 'Draw', 'DrawIndexed', 'DrawInstanced', 'DrawIndexedInstanced', 'DrawAuto',
    'DrawInstancedIndirect', 'DrawIndexedInstancedIndirect', 'Dispatch', 'DispatchIndirect',
    'CSSetUnorderedAccessViews', 'OMSetRenderTargetsAndUnorderedAccessViews', 'ClearUnorderedAccessViewUint',
    'ClearUnorderedAccessViewFloat', 'CopyStructureCount', 'ClearState', 'FinishCommandList', 'ExecuteCommandList',
    'OMSetRenderTargets', 'ClearDepthStencilView', 'CopyResource', 'CopySubresourceRegion',
    'VSSetShaderResources', 'PSSetShaderResources', 'GSSetShaderResources', 'CSSetShaderResources',
}
HANDWRITTEN = {'QueryInterface', 'AddRef', 'Release'}
TARGETS = {
    'ID3D11DeviceChild': 'real_', 'ID3D11DeviceContext': 'real_', 'ID3D11DeviceContext1': 'real1_',
    'ID3D11DeviceContext2': 'real2_', 'ID3D11DeviceContext3': 'real3_', 'ID3D11DeviceContext4': 'real4_',
}


def main():
    header, out = sys.argv[1:]
    text = open(header).read()
    start = text.index('typedef struct ID3D11DeviceContext4Vtbl {')
    body = text[start:text.index('} ID3D11DeviceContext4Vtbl;', start)]
    lines = ['// Generated by tools/gen_context_wrapper.py from MinGW d3d11_3.h. Do not edit.']
    count = 0
    for section in re.split(r'/\*\*\* (\w+) methods \*\*\*/', body)[1:]:
        if section in TARGETS or section == 'IUnknown':
            iface = section
            continue
        for m in re.finditer(r'([\w ]+?\**)\s*\(STDMETHODCALLTYPE \*(\w+)\)\(\s*ID3D11DeviceContext4 \*This,?(.*?)\);',
                             section, re.S):
            ret, name, params = m.group(1).strip(), m.group(2), ' '.join(m.group(3).split())
            if name in HANDWRITTEN:
                continue
            args = []
            for p in [p.strip() for p in params.split(',') if p.strip()]:
                arg = re.sub(r'\[.*?\]', '', p).replace('*', ' ').split()[-1]
                args.append(arg)
            call = f'Hk_{name}(real_, ' if name in INTERCEPTED else f'{TARGETS[iface]}->{name}('
            call = call + ', '.join(args) + ')'
            call = call.replace('(real_, )', '(real_)')
            lines.append(f'{ret} STDMETHODCALLTYPE {name}({params}) override {{ return {call}; }}')
            count += 1
    open(out, 'w').write('\n'.join(lines) + '\n')
    print(count, 'methods')


if __name__ == '__main__':
    main()
