#!/bin/bash
# Compiles src/proxy/shaders/emulation.hlsl with Microsoft's compiler in the VM and writes
# src/proxy/emulation_shaders.h (checked in, so normal builds don't need the VM).
set -e
cd "$(dirname "$0")/.."
VM=tools/vm.sh
out=build/emulation
mkdir -p "$out"
entries="vs_fullscreen:vs_4_0 vs_thread:vs_4_0 gs_signature_float:gs_4_0 gs_signature_uint:gs_4_0 gs_signature_sint:gs_4_0 ps_store_float:ps_4_0 ps_store_uint:ps_4_0 ps_store_sint:ps_4_0 ps_signature_float:ps_4_0 ps_signature_uint:ps_4_0 ps_signature_sint:ps_4_0"
$VM put build/x64/shadertool.exe
$VM put src/proxy/shaders/emulation.hlsl
for e in $entries; do
    name=${e%%:*}
    target=${e##*:}
    $VM ssh "cd /d C:\\dx11on10 && shadertool compile emulation.hlsl $name $target $name.dxbc"
    $VM get "C:/dx11on10/$name.dxbc" "$out/$name.dxbc"
done
python3 - "$out" $entries <<'EOF'
import sys
out, entries = sys.argv[1], sys.argv[2:]
lines = ['// Generated by tools/build_emulation_shaders.sh from src/proxy/shaders/emulation.hlsl. Do not edit.',
         '#pragma once', '#include <cstdint>', '']
for e in entries:
    name = e.split(':')[0]
    data = open(f'{out}/{name}.dxbc', 'rb').read()
    body = ',\n'.join('    ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 16]) for i in range(0, len(data), 16))
    lines += [f'static const uint8_t k_{name}[] = {{', body, '};', '']
open('src/proxy/emulation_shaders.h', 'w').write('\n'.join(lines))
print('wrote src/proxy/emulation_shaders.h')
EOF
